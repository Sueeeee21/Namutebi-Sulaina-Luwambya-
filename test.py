def student_info(name, age, course, student_number):
    print(f"Student Name: {name}\nAge: {age}\nCourse: {course}\nNumber: {student_number}")

name = input("Enter the student's name: ")
age = input("Enter the student's age: ")
course = input("Enter the student's course: ")
student_number = input("Enter the student's number: ")

student_info(name, age, course, student_number)
